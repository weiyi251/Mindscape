// ============================================================================
// 模块说明（中文）
// 操作命令（Command）接口定义。对应开发计划书第十三章「准备 5：操作命令化」。
//
// 每个操作都是一个带 do() / undo() 的命令对象，例如：
//   { type: 'move', cardId: 'c_001', from: {x:0,y:0}, to: {x:100,y:0}, do(){}, undo(){} }
//
// 收益（第 13 章）：
//   · 撤销 / 重做天然支持（由 core/commands/history.ts 统一驱动）
//   · 将来做「操作历史」「协作同步（命令重放）」可直接复用
//   · 调试友好：可完整回放操作序列
//
// 注意（第 7.4 节）：撤销必须**同时回滚文件操作**（如撤销「移除」要把文件从 `_已移除`
// 搬回原位），否则会出现「画布上有图、硬盘上找不到」的状态。因此 do/undo 允许返回 Promise。
// ============================================================================

/**
 * 可撤销的操作单位。
 *
 * 具体命令（move / remove / rename / note / connect / importFiles …）在
 * `core/commands/impl/` 下实现，并通过额外的自有字段携带参数（结构化类型允许扩展）。
 */
export interface Command {
  /** 命令类型标识，如 'move' / 'remove' / 'rename'。用于调试、日志与将来的命令重放。 */
  readonly type: string

  /**
   * 执行。由 History 驱动，也可由业务层直接调用。
   * 允许异步 —— 涉及文件搬运的命令（移除 / 恢复 / 拖入）必须等待落盘完成。
   */
  do(): void | Promise<void>

  /**
   * 撤销。必须把 do() 造成的**视图变化与文件变化**一并还原。
   * 若抛错，History 不会推进指针，调用方可重试或提示用户。
   */
  undo(): void | Promise<void>
}
